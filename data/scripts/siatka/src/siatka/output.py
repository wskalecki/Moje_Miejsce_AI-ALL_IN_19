"""Write outputs in the team contract format (docs/data/grid-schema.md, poi-schema.md)."""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

from siatka.config import DATA_DIR, GRID_PATH, INDICATORS_PATH, MANIFEST_PATH, METRICS_PATH, POI_DIR, README_PATH
from siatka.model import DATASETS
from siatka.personas import PERSONAS
from siatka.pipeline import Result

DEFAULT_PERSONA = "ania_tomek"  # the concept's main user; its sentences fill contract `narrative.pl`
README_START = "<!-- siatka:inventory:start -->"
README_END = "<!-- siatka:inventory:end -->"


def _dump(path: Path, data) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, separators=(",", ":"))


def _rel(path: Path) -> str:
    return path.relative_to(DATA_DIR).as_posix()


def write_all(result: Result) -> dict[str, str]:
    result.ctx.grid.save()
    poi_files = write_poi(result)
    write_metrics(result)
    write_indicators(result, poi_files)
    write_manifest(poi_files)
    write_readme_inventory(result, poi_files)
    return {"grid": _rel(GRID_PATH), "cellMetrics": _rel(METRICS_PATH), "indicators": _rel(INDICATORS_PATH)}


def write_metrics(result: Result) -> None:
    cells = {}
    for cell in result.ctx.grid.cells:
        cid = cell.id
        cells[cid] = {
            "district": cell.district,
            "scores": result.scores[cid],
            "metrics": result.metrics[cid],
            "metrics_norm": result.norms[cid],
            "narrative": {"pl": result.narratives[cid][DEFAULT_PERSONA]},
            "narrative_by_persona": {p: {"pl": s} for p, s in result.narratives[cid].items()},
            "commute_heuristic_min": {},
        }
    _dump(
        METRICS_PATH,
        {
            "schemaVersion": 1,
            "generatedAt": result.generated_at,
            "personas": list(PERSONAS),
            "indicatorsFile": _rel(INDICATORS_PATH),
            "cells": cells,
        },
    )


def write_poi(result: Result) -> list[str]:
    by_category: dict[str, list] = defaultdict(list)
    for key, pois in result.ctx._pois.items():
        if DATASETS[key].publish:
            for p in pois:
                by_category[p.category].append(p.to_feature())
    files = []
    for category, features in sorted(by_category.items()):
        path = POI_DIR / f"{category}.geojson"
        _dump(path, {"type": "FeatureCollection", "features": features})
        files.append(_rel(path))
    return files


def write_indicators(result: Result, poi_files: list[str]) -> None:
    datasets = []
    for key in sorted(result.ctx._pois):
        info = result.ctx.source_info(key)
        info["poiCount"] = len(result.ctx._pois[key])
        datasets.append(info)
    _dump(
        INDICATORS_PATH,
        {
            "generatedAt": result.generated_at,
            "indicators": [i.metadata(result.ctx) for i in result.indicators],
            "personas": PERSONAS,
            "datasets": datasets,
            "poiFiles": poi_files,
        },
    )


def write_manifest(poi_files: list[str]) -> None:
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8")) if MANIFEST_PATH.exists() else {}
    manifest.update(
        {
            "schemaVersion": 1,
            "description": "Full Warsaw outputs generated by data/scripts/siatka (uv run siatka run).",
            "bbox": [20.85, 52.10, 21.28, 52.37],
        }
    )
    manifest["files"] = {
        **manifest.get("files", {}),
        "grid": _rel(GRID_PATH),
        "cellMetrics": _rel(METRICS_PATH),
        "indicators": _rel(INDICATORS_PATH),
        "poi": poi_files,
    }
    with MANIFEST_PATH.open("w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)
        f.write("\n")


def write_readme_inventory(result: Result, poi_files: list[str]) -> None:
    rows = [
        "| Zbiór (dataset) | Źródło | Licencja | Pobrano | POI | Dane miasta |",
        "|---|---|---|---|---|---|",
    ]
    for key in sorted(result.ctx._pois):
        info = result.ctx.source_info(key)
        status = info["fetchedAt"] or ("BŁĄD: " + info["error"][:60] if info["error"] else "—")
        rows.append(
            f"| `{key}` | [{info['name']}]({info['url']}) | {info['license']} | {status} "
            f"| {len(result.ctx._pois[key])} | {'tak' if info['cityOpenData'] else 'nie'} |"
        )
    block = "\n".join(
        [README_START, "", "Generowane przez `uv run siatka run` — nie edytuj ręcznie.", "", *rows, "", README_END]
    )
    text = README_PATH.read_text(encoding="utf-8")
    if README_START in text:
        before, rest = text.split(README_START, 1)
        after = rest.split(README_END, 1)[1]
        text = before + block + after
    else:
        text = text.rstrip() + "\n\n## Inventory — siatka ETL\n\n" + block + "\n"
    README_PATH.write_text(text, encoding="utf-8")
